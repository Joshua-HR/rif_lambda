end


% ======================================================================
function X = read_set(root)
% conditions of the set: root/synthetic_set.txt (gen_synthetic_dumps), or an older 32-symbol set without it.
% The folder names, the AccNum of the file names and the dump format must agree.
d = dir(fullfile(root, 'h0', 'c*_m*_j*'));
lens = [];
for i = 1:numel(d)
    t = regexp(d(i).name, '^c(\d+)_m\d+_j\d+$', 'tokens', 'once');
    if d(i).isdir && ~isempty(t), lens(end + 1) = str2double(t{1}); end %#ok<AGROW>
end
lens = unique(lens);
if numel(lens) ~= 1
    error('run_synthetic_test:set', 'h0/ under "%s" holds job folders of %d RIF lengths (%s); one set per root.', ...
          root, numel(lens), num2str(lens));
end
fn = fullfile(root, 'synthetic_set.txt');
X = struct('N', lens, 'cols', NaN, 'ppm', 0.25, 'drift', 0.3, 'driftSrc', 'Drift', 'S', 0, 'scale', 1, ...
           'legacy', true, 'legacyTag', '', 'amp', NaN, 'T', []);
if exist(fn, 'file') == 2
    m = read_manifest(fn);
    need = {'N', 'Cols', 'Ppm', 'Drift', 'DriftSource', 'PowerShift', 'Scale'};
    miss = need(~isfield(m, need));
    if ~isempty(miss)
        error('run_synthetic_test:set', '%s lacks %s; regenerate the set.', fn, strjoin(miss, ', '));
    end
    X.legacy = false;
    X.N = str2double(m.N); X.cols = str2double(m.Cols); X.ppm = str2double(m.Ppm); X.drift = str2double(m.Drift);
    X.driftSrc = m.DriftSource; X.S = str2double(m.PowerShift); X.scale = str2double(m.Scale);
    if X.N ~= lens
        error('run_synthetic_test:set', '%s says N = %d, but the job folders under h0/ are c%d_...', fn, X.N, lens);
    end
    if X.S ~= power_shift(X.N, X.ppm)
        error('run_synthetic_test:set', '%s: PowerShift %d does not match N = %d, Ppm %g (%d expected).', ...
              fn, X.S, X.N, X.ppm, power_shift(X.N, X.ppm));
    end
else
    if lens ~= 32
        error('run_synthetic_test:set', ['"%s" has no synthetic_set.txt and holds %d-symbol job folders. ' ...
              'Regenerate it with gen_synthetic_dumps(root, ''N'', %d).'], root, lens, lens);
    end
    X.legacyTag = ' (no synthetic_set.txt: older 32-symbol set, drift 0.3 taps)';
end
f82 = fullfile(root, 'h0', sprintf('c%d_m82_j1', X.N), 'bin');
nc = dump_cols(f82);
if nc ~= 2 && nc ~= 5
    error('run_synthetic_test:format', 'h0/c%d_m82_j1 holds %g values per line (expected 2 or 5).', X.N, nc);
end
if isnan(X.cols)
    X.cols = nc;
elseif nc ~= X.cols
    error('run_synthetic_test:set', 'synthetic_set.txt says %d columns, but h0/c%d_m82_j1 holds %g.', X.cols, X.N, nc);
end
f = dir(fullfile(f82, '*_RifCir_AccNum_*.txt'));
t = regexp(f(1).name, '_AccNum_(\d+)_', 'tokens', 'once');
if str2double(t{1}) ~= X.N
    error('run_synthetic_test:set', 'h0/c%d_m82_j1 holds dumps with AccNum %s.', X.N, t{1});
end
if X.legacy
    X.scale = max(2, numel(f)) / 500;                       % 500 fragments per H0 job at Scale 1
    if abs(X.scale - 1) < 0.01, X.scale = 1; end
end
X.amp = amp_factor(X.N, X.ppm);
X.T = synthetic_expect(X.N);
end


% ======================================================================
function m = read_manifest(fn)
m = struct();
lines = regexp(fileread(fn), '\r?\n', 'split');
for i = 1:numel(lines)
    t = regexp(regexprep(lines{i}, '%.*$', ''), '^\s*(\w+)\s*=\s*(.*?)\s*$', 'tokens', 'once');
    if ~isempty(t), m.(t{1}) = t{2}; end
end
end


% ======================================================================
function set_format(root, ncol, N)
% every job folder the run reads must hold dumps of the format and length of the set; a root that still
% holds an older set would otherwise be tested as that older set
bad = {};
subs = {'h0', 'h0_mp20', 'h1', 'h1_drift'};
for s = 1:numel(subs)
    d = dir(fullfile(root, subs{s}, 'c*_m*_j*'));
    for i = 1:numel(d)
        if ~d(i).isdir, continue; end
        b = fullfile(root, subs{s}, d(i).name, 'bin');
        if exist(b, 'dir') ~= 7, b = fullfile(root, subs{s}, d(i).name); end
        if isempty(dir(fullfile(b, '*_RifCir_AccNum_*.txt'))), continue; end
        t = regexp(d(i).name, '^c(\d+)_', 'tokens', 'once');
        nc = dump_cols(b);
        if nc ~= ncol || isempty(t) || str2double(t{1}) ~= N
            bad{end + 1} = sprintf('%s/%s (%g columns)', subs{s}, d(i).name, nc); %#ok<AGROW>
        end
    end
end
if ~isempty(bad)
    error('run_synthetic_test:mixedset', ['h0/c%d_m82_j1 holds %d-column dumps, but these folders differ: %s. ' ...
          'The root mixes two sets; regenerate the set into an empty root.'], N, ncol, strjoin(bad, ', '));
end
if ncol == 2
    stale = {'h0_2col', 'scale_test', 'mixed_test'};
    left = stale(cellfun(@(x) exist(fullfile(root, x), 'dir') == 7, stale));
    if ~isempty(left)
        warning('run_synthetic_test:stale', ['%s under %s belong to a 5-column set (gen_synthetic_dumps with ' ...
                '''Cols'', 2 does not make them); this 2-column run ignores them.'], strjoin(left, ', '), root);
    end
end
end

% ======================================================================
function summary(res, setTag)
banner('summary');
inf_ = [res.info];
nOk = sum([res.ok]);
fprintf('  %d / %d checks OK, %d INFO   (%s)\n', nOk, numel(res) - sum(inf_), sum(inf_), setTag);
for i = find(~[res.ok] & ~inf_)
    fprintf('  CHECK: %s = %.4g (expected %g .. %g)\n', res(i).name, res(i).value, res(i).lo, res(i).hi);
end
fprintf('\n');
end


% ======================================================================
function res = chk(res, X, id, v, name)
% judge value v of check id (its name in the 32-symbol run) with the range of the set; name: printed name
if nargin < 5, name = id; end
[lo, hi, info, note] = range_of(X, id);
ok = ~info && ~isnan(v) && v >= lo && v <= hi;
res(end + 1) = struct('name', name, 'value', v, 'lo', lo, 'hi', hi, 'ok', ok, 'info', info, 'note', note);
if info, tag = 'INFO'; elseif ok, tag = 'OK'; else tag = 'CHECK'; end
if info
    fprintf('  [%-5s] %-58s %10.4g   not judged: %s\n', tag, name, v, note);
else
    fprintf('  [%-5s] %-58s %10.4g   expected %.4g .. %.4g%s\n', tag, name, v, lo, hi, note);
end
end


% ======================================================================
function [lo, hi, info, note] = range_of(X, id)
% range of a check for the set: synthetic_expect(N), then the residual CFO, the drift and Scale of the set
T = X.T; info = false; note = '';
i = find(strcmp(T.id, id), 1);
if isempty(i)
    if numel(id) >= 15 && strcmp(id(end - 14:end), 'condition found')
        lo = 1; hi = 1; return;                             % a missing H0 condition always fails
    end
    error('run_synthetic_test:id', 'No expected range for check "%s" in synthetic_expect.', id);
end
lo = T.lo(i); hi = T.hi(i); ct = T.cat{i}; kind = T.kind{i};
% residual CFO
if any(ct == 'CDEM') && X.amp < 0.5
    info = true; note = sprintf('Ppm %g loses more than 6 dB at N = %d', X.ppm, X.N); return;
end
if abs(X.ppm - 0.25) > 1e-9
    switch T.cfo{i}
        case 'info'
            info = true; note = sprintf('no verified range for Ppm %g (verified: 0.25)', X.ppm); return;
        case 'shift'
            d = cfo_gain(X.N, 0.25) - cfo_gain(X.N, X.ppm);    % L90 moves up by the CFO loss
            lo = lo + d; hi = hi + d; note = sprintf('  (CFO %+.2f dB)', d);
    end
end
% drift of the set
switch T.drift{i}
    case {'slope', 'dmed', 'nhyp'}
        [lo, hi] = drift_range(X.drift, T.drift{i});
    case {'pd', 'gain'}
        if X.drift < T.driftSpan(1) - 1e-6 || X.drift > T.driftSpan(2) + 1e-6
            info = true; note = sprintf('drift %.4g outside the verified %.4g .. %.4g taps/fragment', ...
                                        X.drift, T.driftSpan(1), T.driftSpan(2));
            return;
        end
        if strcmp(T.drift{i}, 'pd'), lo = min(lo, T.driftPdLo); end
end
% reduced set
s = X.scale;
if s < 1 - 1e-9 && ~strcmp(kind, 'fixed')
    if s < 0.1
        info = true; note = sprintf('Scale %g < 0.1: too few fragments to judge', s); return;
    end
    c = T.center(i);
    switch kind
        case 'count'                                        % frames with 8 fragments of max(2, round(500 Scale))
            n = max(2, round(500 * s));
            lo = min(lo, floor(n / 8) / ceil(n / 8) - 0.01);
        case 'rate'
            n = max(2, round(T.n(i) * s));
            lo = min(lo, binq(0.001, n, c) / n);
            hi = max(hi, binq(0.999, n, c) / n);
            if lo == 0, hi = max(hi, 1 / n); end            % one event always allowed
        otherwise
            if ~isnan(c)
                lo = c - (c - lo) / sqrt(s); hi = c + (hi - c) / sqrt(s);
            end
    end
    note = [note sprintf('  (Scale %g)', s)];
end
end


% ======================================================================
function [lo, hi] = drift_range(D, what)
% ranges of the drift checks for a set with peak drift D [taps per fragment] (build_expect.py drift_ranges;
% D = 0.3 gives the ranges of the 32-symbol set before the drift option)
f = 0:7; tru = round(D * f);
x = f - 3.5; si = sum(x .* (tru - mean(tru))) / sum(x .^ 2);   % slope of the integer peak shifts
switch what
    case 'slope'
        lo = round((si - 0.0714) * 100) / 100; hi = round((si + 0.0786) * 100) / 100;
    case 'dmed'
        n = max(3, round(abs(D) * 7) + 1); g = (-n:n) / 7; miss = zeros(size(g));
        for j = 1:numel(g)
            p = round(g(j) * f); best = Inf;
            for c = -3:3, best = min(best, sum(p + c ~= tru)); end
            miss(j) = best;
        end
        b = g(miss == min(miss));
        lo = floor((min(b) - 1 / 7) * 100 + 1e-9) / 100; hi = ceil((max(b) + 1 / 7) * 100 - 1e-9) / 100;
    case 'nhyp'
        if si * 7 > 0.5, c = 2 * ceil(si * 7 - 1e-9) + 1; else c = 1; end
        lo = max(1, c - 2); hi = c + 2;
end
end


% ======================================================================
function k = binq(q, n, p)
% smallest k with P(Binomial(n, p) <= k) >= q
if p <= 0, k = 0; return; end
if p >= 1, k = n; return; end
for k = 0:n - 1
    if betainc(1 - p, n - k, k + 1) >= q, return; end     % P(X <= k)
end
k = n;
end


% ======================================================================
function S = power_shift(N, ppm)
% power shift [dB] of the H1 and drift folders (gen_synthetic_dumps, gen_dumps.py)
S = round(-(cfo_gain(N, ppm) - cfo_gain(32, 0.25)));
end


% ======================================================================
function g = cfo_gain(N, ppm)
g = 10 * log10((N - 1) * amp_factor(N, ppm) ^ 2);
end


% ======================================================================
function a = amp_factor(N, ppm)
% peak amplitude factor sin(x)/x, x = half the CFO phase turned over the N-1 accumulated symbols
x = 2 * pi * 1e-6 * 7987.2e6 * 1024 / 998.4e6 * ppm * (N - 1) / 2;
if x == 0, a = 1; else a = sin(x) / x; end
end


