function res = run_synthetic_test(root, show)
%RUN_SYNTHETIC_TEST  Smoke test of lambda_patch on synthetic RIF CIR dumps (5-column or 2-column, RIF length
%   32 / 64 / 128 / 256 symbols).
%
%   The dump folders under root come from gen_synthetic_dumps.m (or the pre-generated
%   synthetic_dumps/ folder), a waveform model, not the UWB simulator:
%   real +-1 STS, pulse with the comb profile of RIF_CIR_Validity_Detector.md 5.1, residual CFO,
%   coloured thermal noise, N symbols (AccNum N, M = (N-1)*128), peak at tap 127. Each dump has
%   256 lines "re im Q PiRe PiIm" with Q[k] = sum|z|^2 and Pi[k] = sum z^2 over the samples z
%   used for lag k. dBm uses the model mapping of the MD document (-100 dBm <-> per-pulse SNR
%   -11.4 dB), so the numbers are model numbers, not simulator numbers.
%
%       h0/          H0 (key mismatch)  c<N>_m{120,88,82,40}_j{1,2}/bin   500 fragments per job
%       h0_mp20/     H0 -40 dBm, multipath tau_rms 20 ns (diffuse 6 dB above LOS), 2 jobs x 500
%       h1/          H1 (matched key)   c<N>_m106 ... c<N>_m116 (32 symbols; moved by S, see below), 200 each
%       h0_2col/     2-column dumps (old format): MD rule + kappa only, Lambda skipped
%       scale_test/  Q and Pi multiplied by 64 on purpose: the scale warning must appear
%       mixed_test/  first file 2-column, the rest 5-column: 'rif_cir_analyze:mixed' error expected
%       h1_drift/    H1 -114 dBm (400, moved by S) and -90 dBm (80): peak drift inside a packet (frame),
%                    AGC gain -3/0/+3 dB per fragment; for the packet drift search and check_packet_assumptions
%
%   res = run_synthetic_test                    % root = <project>/synthetic_dumps, with figures
%   res = run_synthetic_test('D:/rif_test')     % dumps made by gen_synthetic_dumps('D:/rif_test')
%   res = run_synthetic_test('D:/rif_t64')      % dumps made by gen_synthetic_dumps('D:/rif_t64', 'N', 64)
%   res = run_synthetic_test(root, false)       % no figures
%
%   The set: root/synthetic_set.txt (written by gen_synthetic_dumps) gives the RIF length N, the format,
%   the residual CFO (Ppm), the peak drift, the power shift S and Scale; the folder names (c<N>_), the file
%   names (AccNum_<N>) and the dump format must agree with it (error run_synthetic_test:set otherwise). A root
%   without the file is an older 32-symbol set (Ppm 0.25, drift 0.3 taps, S = 0; Scale from the number of
%   fragments). Every job folder of h0, h0_mp20, h1, h1_drift must have the same format (error
%   run_synthetic_test:mixedset otherwise). The first lines name the set, the summary line counts the checks
%   ("49 / 49 checks OK, 0 INFO (2-column set, N 64, <root>)"):
%     5 columns (gen_synthetic_dumps(root)):            steps 1-10, 94 checks
%     2 columns (gen_synthetic_dumps(root, 'Cols', 2)): the current LLS format; 6 steps, 49 checks on the
%       MD rule, kappa and the CIR-only Lambda-hat ('Moments', 'cir'). Made with the same root and seeds,
%       the 2-column set has the same CIR as the 5-column set, so the MD-rule, kappa and Lambda-hat numbers
%       of the two runs must be identical.
%   The last step checks the packet decision (rif_packet, FiRa medium 1e-6 per packet, 8 RIF fragments per
%   frame): soft sum, AND, one-fragment configuration, drift search on h1_drift/ and
%   check_packet_assumptions; for 'fixed' (Lambda-hat) and, with 5 columns, 'new' (Lambda).
%
%   Expected ranges: synthetic_expect(N) (generated by lambda_patch/model/build_expect.py from Python
%   reference sets of every length; 32 symbols: the ranges of this test before the length support).
%   Checks at a fixed power use the powers of the set (32-symbol power + S, e.g. -110 -> -113 dBm at 64
%   symbols) and print them. Ranges move with the conditions of the set:
%     Ppm ~= 0.25   L90 checks move by the CFO gain formula; kappa and the MD-rule H0 statistics are [INFO]
%                   (no verified range); beyond a 6 dB CFO loss (peak amplitude factor < 0.5) every
%                   CFO-dependent check (kappa, MD-rule H0, H1) is [INFO]
%     drift D       drift slope, selected drift and suggested hypotheses come from D; the drift search uses
%                   (-n:n)/7, n = max(3, round(|D| * 7) + 1); the drift Pd checks are [INFO] outside the
%                   verified drift span (synthetic_expect: driftSpan)
%     Scale < 1     rates: widened to the 0.1 % / 99.9 % binomial interval of the smaller count; other
%                   statistics: half-width / sqrt(Scale); frames with 8 fragments from the counts;
%                   Scale < 0.1: every statistical check is [INFO]
%
%   Every check prints [OK], [CHECK] or [INFO] (value only, not judged) with the expected range. The ranges
%   are wide enough for the statistical spread of these sample sizes; a single CHECK slightly outside is not
%   necessarily a bug. Step 4 also checks the Pd confidence interval and the detection-position accuracy of
%   h1_pd_analyze; step 9 runs the CIR-only variant ('Moments', 'cir'), as on fixed silicon without Q/Pi
%   accumulators. The run rebuilds the per-folder caches (h0_stats_cache.mat) and takes a few minutes.

here = fileparts(mfilename('fullpath'));                   % <project>/lambda_patch/test
patchDir = fileparts(here);                                 % <project>/lambda_patch
if nargin < 1 || isempty(root), root = fullfile(fileparts(patchDir), 'synthetic_dumps'); end
if nargin < 2, show = true; end
if exist(fullfile(root, 'h0'), 'dir') ~= 7
    error('run_synthetic_test:root', 'No h0 folder under "%s". Run gen_synthetic_dumps(root) first.', root);
end
fprintf('dumps: %s\n', root);
addpath(patchDir, '-begin');
fns = {'rif_cir_analyze', 'h0_pfa_analyze', 'h1_pd_analyze', 'rif_packet', 'check_packet_assumptions'};
for i = 1:numel(fns)
    w = which(fns{i});
    fprintf('%-16s -> %s\n', fns{i}, w);
    if isempty(strfind(w, 'lambda_patch'))
        error('run_synthetic_test:path', ['%s does not resolve to the lambda_patch folder. A function file ' ...
              'in the current folder shadows the path: cd to another folder (not the one holding the ' ...
              'original scripts) and run again.'], fns{i});
    end
end
res = struct('name', {}, 'value', {}, 'lo', {}, 'hi', {}, 'ok', {}, 'info', {}, 'note', {});
plt = 'none';
if show, plt = 'both'; end
X = read_set(root);                                          % conditions of the set (N, format, Ppm, drift, S, Scale)
N = X.N; S = X.S; ncol = X.cols; c82 = sprintf('c%d_m82_j1', N);
set_format(root, ncol, N);
setTag = sprintf('%d-column set, N %d, %s', ncol, N, root);
if ncol == 2, nExp = 49; else nExp = 94; end
fprintf('dump format: %d columns (%d checks expected)\n', ncol, nExp);
fprintf('set: N %d, %d columns, Ppm %g, drift %.4g taps/fragment (%s), Scale %g, power shift %+d dB%s\n', ...
        N, ncol, X.ppm, X.drift, X.driftSrc, X.scale, S, X.legacyTag);
if X.amp < 0.5
    fprintf('  Ppm %g loses more than 6 dB at N = %d (peak amplitude factor %.2f): CFO-dependent checks are [INFO]\n', ...
            X.ppm, N, X.amp);
end
if ncol == 2
    res = suite_2col(root, show, plt, res, X);
    summary(res, setTag);
    return;
end

% ------------------------------------------------------------------ 1) one folder
banner('1) rif_cir_analyze on one H0 folder (-82 dBm, job 1)');
r = rif_cir_analyze(fullfile(root, 'h0', c82, 'bin'), 'Quiet', true, 'Plot', plt, 'Index', 1);
res = chk(res, X, '-82 dBm: dumps carry Q/Pi (hasMom)', double(r.hasMom));
res = chk(res, X, '-82 dBm: scale check median(qRatio)', median(r.qRatio));
res = chk(res, X, '-82 dBm: MD rule false-alarm rate', mean(r.valid));
res = chk(res, X, '-82 dBm: Lambda false-alarm rate', mean(r.validL));
res = chk(res, X, '-82 dBm: kappa median', median(r.kappa));
res = chk(res, X, '-82 dBm: Lambda threshold T_Lam', r.T_Lam);

% ------------------------------------------------------------------ 2) H0 set
banner('2) h0_pfa_analyze on h0/ (4 powers x 2 jobs)');
R0 = h0_pfa_analyze(fullfile(root, 'h0'), 'Suggest', false, 'Rebuild', true, 'Plot', show);
res = chk(res, X, 'h0: Lambda table produced (all 5-column)', double(~isempty(R0.EL)));
pw = [R0.cond.pow];
plist = [120 88 82 40];
for q = 1:numel(plist)
    c = find(pw == plist(q), 1);
    if isempty(c)
        res = chk(res, X, sprintf('h0 -%d dBm: condition found', plist(q)), 0);
        continue;
    end
    tag = sprintf('h0 -%d dBm', plist(q));
    res = chk(res, X, [tag ': pooled from 2 job folders'], R0.cond(c).jobs);
    res = chk(res, X, [tag ': MD rule Pfa'], R0.E.pfa(c));
    if ~isempty(R0.EL)
        res = chk(res, X, [tag ': Lambda Pfa'], R0.EL.pfa(c));
        res = chk(res, X, [tag ': per-tap tail ratio t=10'], R0.EL.tailRatio(c, 1));
        res = chk(res, X, [tag ': per-tap tail ratio t=14'], R0.EL.tailRatio(c, 2));
    end
    res = chk(res, X, [tag ': kappa median'], median(R0.cond(c).kappa));
end

% ------------------------------------------------------------------ 3) multipath H0
banner('3) h0_pfa_analyze on h0_mp20/ (-40 dBm, tau_rms 20 ns)');
Rm = h0_pfa_analyze(fullfile(root, 'h0_mp20'), 'Suggest', false, 'Rebuild', true, 'Plot', false);
res = chk(res, X, 'mp20: median D [dB] (comb filled, below the 10 dB gate)', median(Rm.cond(1).D));
res = chk(res, X, 'mp20: MD rule Pfa', Rm.E.pfa(1));
if ~isempty(Rm.EL)
    res = chk(res, X, 'mp20: Lambda Pfa', Rm.EL.pfa(1));
    res = chk(res, X, 'mp20: per-tap tail ratio t=10', Rm.EL.tailRatio(1, 1));
end

% ------------------------------------------------------------------ 4) H1 sensitivity
banner(sprintf('4) h1_pd_analyze on h1/ (%d ... %d dBm)', -106 + S, -116 + S));
R1 = h1_pd_analyze(fullfile(root, 'h1'), 'Plot', show);
res = chk(res, X, 'h1: L90 MD rule [dBm]', R1.L90(1, 1));
res = chk(res, X, 'h1: L90 Lambda [dBm]', R1.L90(1, 2));
res = chk(res, X, 'h1: Lambda gain at L90 [dB]', R1.L90(1, 1) - R1.L90(1, 2));
c110 = find([R1.cond.dBm] == -110 + S, 1);                 % -110 dBm at 32 symbols, moved with the set
if ~isempty(c110)
    cc = R1.cond(c110);
    res = chk(res, X, 'h1 -110 dBm: Lambda Pd inside its 95% CI', double(cc.PdLo(2) <= cc.Pd(2) && cc.Pd(2) <= cc.PdHi(2)), ...
              sprintf('h1 %d dBm: Lambda Pd inside its 95%% CI', -110 + S));
    res = chk(res, X, 'h1 -110 dBm: Lambda CI width', cc.PdHi(2) - cc.PdLo(2), sprintf('h1 %d dBm: Lambda CI width', -110 + S));
end
pdL = arrayfun(@(c) c.Pd(2), R1.cond);
accL = arrayfun(@(c) c.PosAcc(2), R1.cond);
res = chk(res, X, 'h1: worst Lambda position accuracy where Pd >= 0.1', min(accL(pdL >= 0.1)));
res = chk(res, X, 'h1: L90 (position ok) - L90, Lambda [dB]', R1.L90loc(1, 2) - R1.L90(1, 2));

% ------------------------------------------------------------------ 5) HW-like per-class moments
banner('5) h0_pfa_analyze with PerClass = true (one Q/Pi per comb phase)');
Rp = h0_pfa_analyze(fullfile(root, 'h0'), 'Suggest', false, 'PerClass', true, 'Plot', false);
if ~isempty(Rp.EL)
    res = chk(res, X, 'PerClass: worst Lambda Pfa over conditions', max(Rp.EL.pfa));
    res = chk(res, X, 'PerClass: smallest tail ratio t=10', min(Rp.EL.tailRatio(:, 1)));
    res = chk(res, X, 'PerClass: largest tail ratio t=10', max(Rp.EL.tailRatio(:, 1)));
end

% ------------------------------------------------------------------ 6) old 2-column dumps
banner('6) 2-column dumps (old format)');
r2 = rif_cir_analyze(fullfile(root, 'h0_2col', c82, 'bin'), 'Quiet', true, 'Plot', 'none');
res = chk(res, X, '2col: hasMom is false', double(r2.hasMom));
res = chk(res, X, '2col: Lmax is NaN for every fragment', double(all(isnan(r2.Lmax))));
res = chk(res, X, '2col: kappa still computed (median)', median(r2.kappa));
R2 = h0_pfa_analyze(fullfile(root, 'h0_2col'), 'Suggest', false, 'Rebuild', true, 'Plot', false);
res = chk(res, X, '2col: h0_pfa_analyze skips Lambda (EL empty)', double(isempty(R2.EL)));

% ------------------------------------------------------------------ 7) scale mismatch
banner('7) Q/Pi scaled by 64 on purpose: a scale warning must appear below');
lastwarn('');
r3 = rif_cir_analyze(fullfile(root, 'scale_test', c82, 'bin'), 'Quiet', true, 'Plot', 'none');
[~, wid] = lastwarn;
res = chk(res, X, 'scale: warning rif_cir_analyze:scale raised', double(strcmp(wid, 'rif_cir_analyze:scale')));
res = chk(res, X, 'scale: median(qRatio) close to 1/64', median(r3.qRatio));

% ------------------------------------------------------------------ 8) mixed formats
banner('8) one 2-column file among 5-column files: an error is expected');
eid = '';
try
    rif_cir_analyze(fullfile(root, 'mixed_test', c82, 'bin'), 'Quiet', true, 'Plot', 'none');
catch err
    eid = err.identifier;
    fprintf('  caught: %s\n', err.message);
end
res = chk(res, X, 'mixed: error rif_cir_analyze:mixed raised', double(strcmp(eid, 'rif_cir_analyze:mixed')));

% ------------------------------------------------------------------ 9) CIR-only moments (fixed silicon)
banner('9) ''Moments'', ''cir'': Q/Pi estimated from the CIR (no raw-sample accumulators)');
rc = rif_cir_analyze(fullfile(root, 'h0', c82, 'bin'), 'Quiet', true, 'Plot', 'none', 'Moments', 'cir');
res = chk(res, X, 'cir -82 dBm: Lambda computed from the CIR', double(strcmp(rc.lamMode, 'cir')));
res = chk(res, X, 'cir -82 dBm: fewest noise taps per phase', min(rc.nCir));
res = chk(res, X, 'cir -82 dBm: Lambda false-alarm rate', mean(rc.validL));
R0c = h0_pfa_analyze(fullfile(root, 'h0'), 'Suggest', false, 'Moments', 'cir', 'Plot', false);
if ~isempty(R0c.EL)
    res = chk(res, X, 'cir h0: worst Lambda Pfa over conditions', max(R0c.EL.pfa));
    res = chk(res, X, 'cir h0: smallest tail ratio t=10', min(R0c.EL.tailRatio(:, 1)));
    res = chk(res, X, 'cir h0: largest tail ratio t=10', max(R0c.EL.tailRatio(:, 1)));
end
R2c = h0_pfa_analyze(fullfile(root, 'h0_2col'), 'Suggest', false, 'Moments', 'cir', 'Plot', false);
res = chk(res, X, 'cir 2col: Lambda evaluated on 2-column dumps', double(~isempty(R2c.EL)));
R1c = h1_pd_analyze(fullfile(root, 'h1'), 'Moments', 'cir', 'Plot', false);
res = chk(res, X, 'cir h1: L90 loss vs dumped Q/Pi [dB]', R1c.L90(1, 2) - R1.L90(1, 2));

% ------------------------------------------------------------------ 10) packet decision
banner('10) packet decision (rif_packet): FiRa medium 1e-6 per packet, 8 RIF fragments');
res = suite_packet(root, 'new', show, res, 'pkt', X);
res = suite_packet(root, 'fixed', show, res, 'pkt', X);

% ------------------------------------------------------------------ summary
summary(res, setTag);
end


% ======================================================================
function res = suite_packet(root, chip, show, res, pre, X)
% packet decision for one chip mode; the assumption checks run once, with 'fixed'. Checks at a fixed power
% use the powers of the set (32-symbol power + S); their id stays the 32-symbol name
tag = sprintf('%s %s', pre, chip); S = X.S;
pn = @(name, p32) strrep([tag name], sprintf('%d dBm', p32), sprintf('%d dBm', p32 + S));
P0 = h0_pfa_analyze(fullfile(root, 'h0'), 'Suggest', false, 'Chip', chip, 'Profile', 'fira-medium', 'Plot', show);   % = soft, 1e-6
res = chk(res, X, [tag ' h0 soft: packet threshold T'], P0.pkInfo.T);
res = chk(res, X, [tag ' h0 soft: packets accepted (all conditions)'], sum([P0.PK.k]));
tr = arrayfun(@(x) x.tailRatio(1), P0.PK);
res = chk(res, X, [tag ' h0 soft: smallest tail ratio at P = 1e-2'], min(tr));
res = chk(res, X, [tag ' h0 soft: largest tail ratio at P = 1e-2'], max(tr));
res = chk(res, X, [tag ' h0: largest |correlation| of fragment pairs'], max(abs([P0.PK.rhoPair])));
Pa = h0_pfa_analyze(fullfile(root, 'h0'), 'Suggest', false, 'Chip', chip, 'Combine', 'and', 'Plot', false);
res = chk(res, X, [tag ' h0 and: largest per-fragment rate (budget 0.178)'], max([Pa.PK.fragRate]));
res = chk(res, X, [tag ' h0 and: every condition within the budget'], double(all([Pa.PK.budgetOk] == 1)));

H = h1_pd_analyze(fullfile(root, 'h1'), 'Chip', chip, 'Profile', 'fira-medium', 'Plot', false);
pd = [H.pkt.cond.Pd]; acc = [H.pkt.cond.PosAcc]; db = [H.pkt.cond.dBm];
res = chk(res, X, [tag ' h1 soft: packet Pd at -116 dBm'], sum(pd(db == -116 + S)), pn(' h1 soft: packet Pd at -116 dBm', -116));
res = chk(res, X, [tag ' h1 soft: worst packet position accuracy'], min(acc(pd >= 0.1)));
Ha = h1_pd_analyze(fullfile(root, 'h1'), 'Chip', chip, 'Combine', 'and', 'Plot', false);
res = chk(res, X, [tag ' h1 and: packet L90 [dBm]'], Ha.pkt.L90(1));
Hs = h1_pd_analyze(fullfile(root, 'h1'), 'Chip', chip, 'Combine', 'single', 'FragPerPacket', 1, 'Plot', false);
if strcmp(chip, 'new')
    res = chk(res, X, [tag ' h1 one fragment (1e-6): L90 [dBm]'], Hs.pkt.L90(1));
else
    pd1 = [Hs.pkt.cond.Pd]; db1 = [Hs.pkt.cond.dBm];
    res = chk(res, X, [tag ' h1 one fragment (1e-6): Pd at -106 dBm'], sum(pd1(db1 == -106 + S)), ...
              pn(' h1 one fragment (1e-6): Pd at -106 dBm', -106));
    res = chk(res, X, [tag ' h1 one fragment (1e-6): Pd at -110 dBm'], sum(pd1(db1 == -110 + S)), ...
              pn(' h1 one fragment (1e-6): Pd at -110 dBm', -110));
end

dr = fullfile(root, 'h1_drift');
if exist(dr, 'dir') == 7
    Hd0 = h1_pd_analyze(dr, 'Chip', chip, 'Combine', 'soft', 'Plot', false);
    n = max(3, round(abs(X.drift) * 7) + 1);              % drift search (-n:n)/7 covers the drift of the set
    Hd = h1_pd_analyze(dr, 'Chip', chip, 'Combine', 'soft', 'Drift', (-n:n) / 7, 'Plot', false);
    c = find([Hd.pkt.cond.dBm] == -114 + S, 1);
    res = chk(res, X, [tag ' drift: -114 dBm packet Pd with drift search'], Hd.pkt.cond(c).Pd, ...
              pn(' drift: -114 dBm packet Pd with drift search', -114));
    res = chk(res, X, [tag ' drift: Pd gain of the drift search'], Hd.pkt.cond(c).Pd - Hd0.pkt.cond(c).Pd);
    res = chk(res, X, [tag ' drift: median selected drift [taps/fragment]'], Hd.pkt.cond(c).dMed);
    if strcmp(chip, 'fixed')
        A1 = check_packet_assumptions(dr, '', 'Plot', false);
        res = chk(res, X, [pre ' assumptions: drift slope median [taps/fragment]'], median(A1.drift.slopes));
        res = chk(res, X, [pre ' assumptions: suggested drift hypotheses'], numel(A1.suggest.Drift));
        res = chk(res, X, [pre ' assumptions: AGC level std [dB]'], A1.agc.std);
    end
else
    fprintf('  (no h1_drift folder under %s: drift checks skipped; regenerate the set)\n', root);
end
if strcmp(chip, 'fixed')
    A0 = check_packet_assumptions('', fullfile(root, 'h0'), 'Plot', false);
    res = chk(res, X, [pre ' assumptions: share of frames with 8 fragments'], sum(A0.layout.share(A0.layout.counts == 8)));
    res = chk(res, X, [pre ' assumptions: fragment-pair correlation (H0)'], A0.indep.rho);
end
end


% ======================================================================
function res = suite_2col(root, show, plt, res, X)
% 2-column dumps (current LLS format): MD rule, kappa and the CIR-only Lambda-hat
S = X.S; c82 = sprintf('c%d_m82_j1', X.N);
banner('2-column set: 1) one H0 folder (-82 dBm, job 1)');
r = rif_cir_analyze(fullfile(root, 'h0', c82, 'bin'), 'Quiet', true, 'Plot', plt, 'Index', 1);
res = chk(res, X, '2col -82 dBm: no Q/Pi columns (hasMom false)', double(r.hasMom));
res = chk(res, X, '2col -82 dBm: raw Lambda not computed (Lmax NaN)', double(all(isnan(r.Lmax))));
res = chk(res, X, '2col -82 dBm: MD rule false-alarm rate', mean(r.valid));
res = chk(res, X, '2col -82 dBm: kappa median', median(r.kappa));
rc = rif_cir_analyze(fullfile(root, 'h0', c82, 'bin'), 'Quiet', true, 'Plot', 'none', 'Moments', 'cir');
res = chk(res, X, '2col -82 dBm: Lambda-hat computed from the CIR', double(strcmp(rc.lamMode, 'cir')));
res = chk(res, X, '2col -82 dBm: fewest noise taps per phase', min(rc.nCir));
res = chk(res, X, '2col -82 dBm: Lambda-hat false-alarm rate', mean(rc.validL));

banner('2-column set: 2) h0_pfa_analyze on h0/, MD rule (raw Lambda skipped)');
R0 = h0_pfa_analyze(fullfile(root, 'h0'), 'Suggest', false, 'Rebuild', true, 'Plot', show);
res = chk(res, X, '2col h0: raw Lambda skipped (EL empty)', double(isempty(R0.EL)));
pw = [R0.cond.pow];
plist = [120 88 82 40];
for q = 1:numel(plist)
    c = find(pw == plist(q), 1);
    if isempty(c)
        res = chk(res, X, sprintf('2col h0 -%d dBm: condition found', plist(q)), 0);
        continue;
    end
    tag = sprintf('2col h0 -%d dBm', plist(q));
    res = chk(res, X, [tag ': MD rule Pfa'], R0.E.pfa(c));
    res = chk(res, X, [tag ': kappa median'], median(R0.cond(c).kappa));
end

banner('2-column set: 3) h0_pfa_analyze on h0/ with ''Moments'', ''cir''');
R0c = h0_pfa_analyze(fullfile(root, 'h0'), 'Suggest', false, 'Moments', 'cir', 'Plot', show);
res = chk(res, X, '2col h0 cir: Lambda-hat table produced', double(~isempty(R0c.EL)));
if ~isempty(R0c.EL)
    res = chk(res, X, '2col h0 cir: worst Lambda-hat Pfa over conditions', max(R0c.EL.pfa));
    res = chk(res, X, '2col h0 cir: smallest tail ratio t=10', min(R0c.EL.tailRatio(:, 1)));
    res = chk(res, X, '2col h0 cir: largest tail ratio t=10', max(R0c.EL.tailRatio(:, 1)));
end

banner('2-column set: 4) multipath H0 (h0_mp20/)');
Rm = h0_pfa_analyze(fullfile(root, 'h0_mp20'), 'Suggest', false, 'Moments', 'cir', 'Rebuild', true, 'Plot', false);
res = chk(res, X, '2col mp20: median D [dB] (below the 10 dB gate)', median(Rm.cond(1).D));
res = chk(res, X, '2col mp20: MD rule Pfa', Rm.E.pfa(1));
if ~isempty(Rm.EL)
    res = chk(res, X, '2col mp20 cir: Lambda-hat Pfa', Rm.EL.pfa(1));
end

banner('2-column set: 5) H1 (h1/): MD rule and Lambda-hat');
R1 = h1_pd_analyze(fullfile(root, 'h1'), 'Plot', false);
res = chk(res, X, '2col h1: L90 MD rule [dBm]', R1.L90(1, 1));
res = chk(res, X, '2col h1: raw Lambda not available (Pd = 0)', max(R1.table(:, 5)));
R1c = h1_pd_analyze(fullfile(root, 'h1'), 'Moments', 'cir', 'Plot', show);
res = chk(res, X, '2col h1 cir: L90 Lambda-hat minus L90 MD [dB]', R1c.L90(1, 2) - R1c.L90(1, 1));
pdL = arrayfun(@(x) x.Pd(2), R1c.cond);
accL = arrayfun(@(x) x.PosAcc(2), R1c.cond);
res = chk(res, X, '2col h1 cir: worst position accuracy where Pd >= 0.1', min(accL(pdL >= 0.1)));
c110 = find([R1c.cond.dBm] == -110 + S, 1);                % -110 dBm at 32 symbols, moved with the set
if ~isempty(c110)
    cc = R1c.cond(c110);
    res = chk(res, X, '2col h1 cir -110 dBm: Pd inside its 95% CI', double(cc.PdLo(2) <= cc.Pd(2) && cc.Pd(2) <= cc.PdHi(2)), ...
              sprintf('2col h1 cir %d dBm: Pd inside its 95%% CI', -110 + S));
    res = chk(res, X, '2col h1 cir -110 dBm: CI width', cc.PdHi(2) - cc.PdLo(2), sprintf('2col h1 cir %d dBm: CI width', -110 + S));
end

banner('2-column set: 6) packet decision (rif_packet, fixed chip): FiRa medium 1e-6 per packet');
res = suite_packet(root, 'fixed', show, res, '2col pkt', X);
end


% ======================================================================
function nc = dump_cols(folder)
f = dir(fullfile(folder, '*_RifCir_AccNum_*.txt'));
if isempty(f)
    error('run_synthetic_test:nodump', 'No dump files in "%s".', folder);
end
fid = fopen(fullfile(folder, f(1).name), 'r');
